import { randomUUID } from "node:crypto";
import { isAuthorizedDeviceToken, readBearerToken } from "@/lib/device-auth";
import { routeAssistantRequest } from "@/lib/llm-router";
import { AssistantRequestSchema, filterProposedActions } from "@/lib/protocol";
import { createRateLimiter } from "@/lib/rate-limit";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const MAX_BODY_BYTES = 16 * 1024;
const encoder = new TextEncoder();
const allowRequest = createRateLimiter(30, 60_000);

async function readJsonBounded(request: Request): Promise<unknown> {
  const declaredLength = Number(request.headers.get("content-length") ?? "0");
  if (declaredLength > MAX_BODY_BYTES) throw new Error("BODY_TOO_LARGE");
  if (!request.body) throw new Error("INVALID_BODY");

  const reader = request.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > MAX_BODY_BYTES) {
      await reader.cancel();
      throw new Error("BODY_TOO_LARGE");
    }
    chunks.push(value);
  }
  const bytes = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.byteLength; }
  return JSON.parse(new TextDecoder().decode(bytes));
}

function sseResponse(signal: AbortSignal, run: (send: (event: unknown) => void) => Promise<void>): Response {
  let closed = false;
  const body = new ReadableStream<Uint8Array>({
    async start(controller) {
      // Safe after client disconnect: stop emitting instead of throwing.
      const send = (event: unknown) => {
        if (closed || signal.aborted) return;
        try { controller.enqueue(encoder.encode(`data: ${JSON.stringify(event)}\n\n`)); }
        catch { closed = true; }
      };
      try { await run(send); }
      catch (error) {
        console.error("assistant_request_failed", error instanceof Error ? error.name : "unknown");
        send({ type: "error", code: "INTERNAL", message: "Assistant request failed" });
      }
      finally {
        if (!closed) { closed = true; try { controller.close(); } catch { /* already closed */ } }
      }
    },
    cancel() { closed = true; }
  });
  return new Response(body, {
    status: 200,
    headers: {
      "Content-Type": "text/event-stream; charset=utf-8",
      "Cache-Control": "no-cache, no-transform",
      "Connection": "keep-alive",
      "X-Accel-Buffering": "no",
      "X-Content-Type-Options": "nosniff"
    }
  });
}

export async function POST(request: Request): Promise<Response> {
  const token = readBearerToken(request.headers.get("authorization"));
  if (!isAuthorizedDeviceToken(token)) return Response.json({ error: "Unauthorized" }, { status: 401 });

  if (!allowRequest("device")) {
    return Response.json({ error: "Rate limited" }, { status: 429, headers: { "Retry-After": "60" } });
  }

  let parsed: unknown;
  try { parsed = await readJsonBounded(request); }
  catch (error) {
    const tooLarge = error instanceof Error && error.message === "BODY_TOO_LARGE";
    return Response.json({ error: tooLarge ? "Payload too large" : "Invalid JSON body" }, { status: tooLarge ? 413 : 400 });
  }

  const validation = AssistantRequestSchema.safeParse(parsed);
  if (!validation.success) return Response.json({ error: "Invalid request" }, { status: 400 });

  return sseResponse(request.signal, async (send) => {
    const result = await routeAssistantRequest(validation.data);
    // Reply is generated by Gemini; emit in bounded pieces using the Android client's existing SSE contract.
    for (let offset = 0; offset < result.reply.length; offset += 160) {
      send({ type: "text_delta", delta: result.reply.slice(offset, offset + 160) });
    }

    const actions = filterProposedActions(result.actions);
    if (actions.length) {
      const planId = randomUUID();
      send({
        type: "plan",
        planId,
        steps: actions.map((action, index) => ({
          stepNumber: index + 1,
          tool: action.tool,
          description: `Proposed ${action.tool.replaceAll("_", " ")}`
        }))
      });
      for (const action of actions) {
        send({
          type: "action",
          actionId: randomUUID(),
          tool: action.tool,
          args: action.args,
          suggestedRisk: "HIGH",
          requiresConsent: true,
          allowParallel: false
        });
      }
    }
    send({ type: "done" });
  });
}
